"""Generate results_macros.tex from the benchmark's results/analysis JSON.

Every number in the paper's Results section is a macro produced by this script
from the committed run artifacts — none are typed by hand.

Run:  python3 gen_macros.py
"""

from __future__ import annotations

import json
import os

PAPER_DIR = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(PAPER_DIR, "..", "benchmark", "results")


def pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}"


def latex_sci(x: float) -> str:
    """Format a small number as LaTeX scientific notation for math mode."""
    if x >= 0.001:
        return f"{x:.3g}"
    mantissa, exponent = f"{x:.1e}".split("e")
    return f"{mantissa} \\times 10^{{{int(exponent)}}}"


def main() -> None:
    with open(os.path.join(RESULTS_DIR, "results.json")) as fh:
        results = json.load(fh)
    with open(os.path.join(RESULTS_DIR, "analysis.json")) as fh:
        analysis = json.load(fh)

    ps = analysis["prompt_level_strict"]
    pl = analysis["prompt_level_loose"]
    cov = analysis["instruction_level_strict_by_coverage"]
    gate = analysis["gate_dynamics"]
    cost = analysis["cost"]

    n_instr = cov["all"]["n_instances"]
    macros = {
        "NPrompts": str(results["n_prompts_total"]),
        "NPromptsPaired": str(analysis["n_prompts_paired"]),
        "NInstrInstances": str(n_instr),
        # prompt-level strict
        "ControlPromptStrict": pct(ps["control_accuracy"]),
        "TreatmentPromptStrict": pct(ps["treatment_accuracy"]),
        "DeltaPromptStrict": pct(ps["delta"]),
        "DeltaCILow": pct(ps["bootstrap_95ci_delta"][0]),
        "DeltaCIHigh": pct(ps["bootstrap_95ci_delta"][1]),
        "McNemarP": latex_sci(ps["mcnemar_exact_p_value"]),
        "DiscordantTreatOnly": str(ps["mcnemar_discordant_treatment_only_pass"]),
        "DiscordantControlOnly": str(ps["mcnemar_discordant_control_only_pass"]),
        # prompt-level loose
        "ControlPromptLoose": pct(pl["control_accuracy"]),
        "TreatmentPromptLoose": pct(pl["treatment_accuracy"]),
        "DeltaPromptLoose": pct(pl["delta"]),
        # instruction-level strict (official scorer, all instances)
        "ControlInstrStrict": pct(results["control"]["instruction_level_strict_accuracy"]),
        "TreatmentInstrStrict": pct(results["treatment"]["instruction_level_strict_accuracy"]),
        # gate dynamics
        "GateInitialFail": str(gate["prompts_failing_charter_initially"]),
        "GateFinalFail": str(gate["prompts_failing_charter_after_gate"]),
        "GateSelectedRevision": str(gate["prompts_where_gate_selected_a_revision"]),
        # cost
        "ExtraCalls": str(cost["treatment_extra_model_calls"]),
        "PromptsWithRevision": str(cost["prompts_with_at_least_one_revision"]),
        "MeanRevisions": f"{cost['mean_revisions_per_prompt']:.2f}",
        "MeanCharsControl": f"{cost['mean_response_chars_control']:.0f}",
        "MeanCharsTreatment": f"{cost['mean_response_chars_treatment']:.0f}",
    }

    for klass, prefix in (("exact", "Exact"), ("approx", "Approx"), ("uncovered", "Uncovered"), ("all", "All")):
        row = cov[klass]
        macros[f"{prefix}N"] = str(row["n_instances"])
        macros[f"{prefix}Pct"] = pct(row["n_instances"] / n_instr)
        macros[f"{prefix}Control"] = pct(row["control_accuracy"])
        macros[f"{prefix}Treat"] = pct(row["treatment_accuracy"])
        macros[f"{prefix}Delta"] = pct(row["delta"])

    lines = ["% Auto-generated by gen_macros.py from benchmark/results/*.json — do not edit by hand."]
    for name, value in macros.items():
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")
    out = os.path.join(PAPER_DIR, "results_macros.tex")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {out} with {len(macros)} macros")


if __name__ == "__main__":
    main()
